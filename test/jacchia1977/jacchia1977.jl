    for h in (150e3, 400e3, 1000e3)
        expected = AtmosphericModels.jacchia1977(
            instant, ϕ_gd, λ, h, F10, F10ₐ, Kp; variant = Val(:stela)
        )
        result = AtmosphericModels.jacchia1977(instant, ϕ_gd, λ, h; variant = Val(:stela))

