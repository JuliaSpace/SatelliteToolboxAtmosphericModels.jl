# The files ja77_stat.dat and ja77_dynm.dat contain the reference outputs of the Fortran
# implementation of the Jacchia 1977 model [2], developed at the Instituto Nacional de
# Pesquisas Espaciais (INPE) by Bento Silva de Matos and Valdemir Carrara. They were
# obtained from the archive:
#
#     https://github.com/jacobwilliams/INPE-atmosphere-models
